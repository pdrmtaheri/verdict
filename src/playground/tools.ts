export const LAWS_FILE = "VERDICT.md";
export const LOCK_FILE = "VERDICT.lock";

// Files the agent can never write with write_file: laws go through write_laws,
// the lock is generated, and the manifest is the playground's own definition.
const PROTECTED = new Set([LAWS_FILE, LOCK_FILE, MANIFEST_FILE]);

// Resolves a path the agent wants to write: relative, inside one of the
// manifest's writable top-level directories, not through a symlink out of it.
export function writablePath(root: string, writable: string[], path: string, versions: string[] = []): string {
  const rel = normalize(path);
  if (isAbsolute(rel) || rel === ".." || rel.startsWith(`..${  sep}`)) throw new Error(`${path} is outside the playground: use a path relative to its root`);
  const parts = rel.split(sep);
  if (PROTECTED.has(rel)) throw new Error(`${rel} can't be written with write_file: use write_laws for ${LAWS_FILE}; ${LOCK_FILE} is generated by plan`);
  // versions/<id>/<code dir>/...: the code of another version
  if (parts[0] === "versions") {
    const [, id, top] = parts;
    if (!id || !versions.includes(id)) throw new Error(`${path}: there is no version "${id ?? ""}" (versions: ${versions.join(", ") || "none"}). Create one by adding a folder under versions/ in the playground`);
    if (!top || !writable.includes(top) || top === ".verdict") throw new Error(`${path} is not in a code directory of version ${id}: write under ${writable.filter((d) => d !== ".verdict").map((d) => `versions/${id}/${d}`).join(", ")}`);
    const dir = join(root, "versions", id, top);
    inside(root, join("versions", id)); // the version folder must not be a link out
    mkdirSync(dir, { recursive: true });
    return inside(root, rel, dir);
  }
  const top = parts[0]!;
  if (!writable.includes(top)) throw new Error(`${path} is not in a writable directory: write under ${writable.join(", ")}`);
  const dir = join(root, top);
  inside(root, top); // the writable directory itself must not be a link out
  mkdirSync(dir, { recursive: true });
  return inside(root, rel, dir);
}

export interface PlaygroundState {
  last: LawReport[] | null; // the latest report, for whichever version was checked
  byVersion: Record<string, LawReport[]>; // the latest report per version
  // While a version is being checked: the laws that have finished so far, so the
  // page can show a fast law's result without waiting for the slowest one.
  running: Record<string, LawReport[]>;
  onProgress?: () => void; // called when a law of a running check finishes
}

export const newState = (): PlaygroundState => ({ last: null, byVersion: {}, running: {} });

// Runs every law's enforcers on one version's code. Nothing is copied or
// changed: each enforcer is given the version's folder as its target, and the
// sandbox is read-only apart from its own temp directory. The code was written
// by an agent, so it never runs unconfined.
export async function checkVersion(root: string, m: Manifest, version: string, onLaw: (report: LawReport) => void = () => {}): Promise<LawReport[]> {
  const target = versionTarget(root, m, version);
  const laws = parseLaws(existsSync(join(root, LAWS_FILE)) ? readFileSync(join(root, LAWS_FILE), "utf8") : "");
  const lock = readLock(join(root, LOCK_FILE));
  return Promise.all(
    laws.map(async (law): Promise<LawReport> => {
      const entry = lock.get(law.hash);
      // Main also replays a break when its pinned inputs changed; another version's code is not what the breaks were made against.
      const report: LawReport = entry
        ? await checkLaw(at(root), entry, { sandbox: { readable: [target], writable: [] }, target, exclude: target === root ? ["versions"] : undefined, hash: law.hash, replay: target === root ? undefined : false })
        : { law: law.text, status: "unplanned", details: [] };
      onLaw(report);
      return report;
    }),
  );
}

export function playgroundTools(root: string, state: PlaygroundState, log: (line: string) => void = () => {}): Tools {
  const manifest = () => loadManifest(root); // re-read: the user may edit it while running
  const read = readTools(root);
  const lawsPath = join(root, LAWS_FILE);
  const laws = () => parseLaws(existsSync(lawsPath) ? readFileSync(lawsPath, "utf8") : "");

  const runCheck = async ({ version }: { version?: string } = {}) => {
    if (laws().length === 0) return "no laws yet: write some with write_laws";
    const m = manifest();
    const v = version ?? MAIN;
    if (!hasVersion(root, m, v)) throw new Error(`there is no version "${v}": use one of ${versionList(root, m).map((x) => x.id).join(", ")}`);
    const done: LawReport[] = [];
    state.running[v] = done;
    let report: LawReport[];
    try {
      report = await checkVersion(root, m, v, (r) => {
        done.push(r);
        state.onProgress?.();
      });
    } finally {
      delete state.running[v];
    }
    state.last = state.byVersion[v] = report;
    return `${versionList(root, m).length > 1 ? `version ${v}\n` : ""}${format(report)}`;
  };

  return {
    get_brief: defineTool({
      description: "Start here. Returns the playground's idea, the brief you work to, the current laws, and the latest check report.",
      schema: z.object({}),
      execute: async () => {
        const m = manifest();
        const report = state.last ? format(state.last) : "(not checked yet: call check)";
        const vs = versionList(root, m);
        const versions = vs.length > 1 ? ["", "## Versions", ...vs.map((v) => `- ${v.id}${v.id === MAIN ? " (the code in the playground's own folders)" : ` (versions/${v.id}/)`}: ${v.label}${v.note ? `. ${v.note}` : ""}`), "The laws are the same for every version; check and run_tests take a version."] : [];
        return [`# ${m.title}`, m.idea, "", "## Brief", m.brief, ...versions, "", "## Laws (VERDICT.md)", existsSync(lawsPath) ? readFileSync(lawsPath, "utf8") : "(none)", "", "## Latest check", report, "", `You may write files under: ${m.writable.join(", ")}`].join("\n");
      },
    }),
    read_laws: defineTool({
      description: "Read VERDICT.md, the playground's laws.",
      schema: z.object({}),
      execute: async () => (existsSync(lawsPath) ? readFileSync(lawsPath, "utf8") : "(no VERDICT.md yet)"),
    }),
    write_laws: defineTool({
      description: "Replace VERDICT.md. One top-level bullet is one law; indented lines continue it. Reworded laws become unplanned until `plan` runs.",
      schema: z.object({ markdown: z.string().describe("The whole new VERDICT.md") }),
      execute: async ({ markdown }) => {
        const n = parseLaws(markdown).length;
        if (n === 0) throw new Error("that has no laws: write each law as a top-level bullet (- ...)");
        writeFileSync(lawsPath, markdown.endsWith("\n") ? markdown : `${markdown  }\n`);
        return `wrote ${n} law${n === 1 ? "" : "s"}; run plan to plan new or reworded ones`;
      },
    }),
    plan: defineTool({
      description: "Plan how each new or reworded law is enforced, and re-prove the existing laws. Uses the playground's configured coding agent (VERDICT_AGENT), so it can take minutes.",
      schema: z.object({}),
      execute: async () => {
        const lines: string[] = [];
        const set = { ...at(root), lockFile: join(root, LOCK_FILE), laws: laws(), lock: readLock(join(root, LOCK_FILE)) };
        const ok = await plan(set, (l) => {
          lines.push(l);
          log(l);
        });
        return `${ok ? "planned" : "plan finished with problems"}\n${lines.join("\n")}`;
      },
    }),
    check: defineTool({
      description: "Run every law's enforcers on one version's code. The default version is main. Each law is pass, fail, inconclusive, or not planned.",
      schema: z.object({ version: z.string().optional().describe("A version id from get_brief. Default main") }),
      execute: runCheck,
    }),
    list_files: read.list_files,
    read_file: read.read_file,
    grep: read.grep,
    write_file: defineTool({
      description: "Create or overwrite a file under one of the playground's writable directories (see get_brief), or under versions/<id>/<directory>/ to write another version's code.",
      schema: z.object({
        path: z.string().describe("Relative to the playground root, such as src/limiter.ts or versions/no-all-red/public/controller.js"),
        content: z.string(),
        executable: z.boolean().optional(),
      }),
      execute: async ({ path, content, executable }) => {
        const m = manifest();
        const abs = writablePath(root, m.writable, path, versionList(root, m).map((v) => v.id).filter((id) => id !== MAIN));
        mkdirSync(dirname(abs), { recursive: true });
        writeFileSync(abs, content, { mode: executable ? 0o755 : 0o644 });
        return `wrote ${relative(root, abs)}`;
      },
    }),
    run_tests: defineTool({
      description: "Run one test file the way verdict would. verdict infers the runner (bun, vitest, jest, go, or pytest) from the file name. The test runs in a read-only sandbox, so it can't change the playground, read your home directory, or reach the network. For an enforcer in .verdict/, version picks the code it looks at (VERDICT_TARGET).",
      schema: z.object({ path: z.string().describe("Test file, relative to the playground root"), version: z.string().optional().describe("The version whose code an enforcer looks at. Default main") }),
      execute: async ({ path, version }) => {
        inside(root, path);
        if (!existsSync(join(root, path))) throw new Error(`${path} does not exist: write it first`);
        const m = manifest();
        const target = versionTarget(root, m, version ?? MAIN);
        const argv = testCommand(root, path)?.argv;
        if (!argv) throw new Error(`don't know how to run ${path}: name it *.test.ts, *_test.go or test_*.py, or make it executable`);
        const [program = ""] = argv;
        if (!program.startsWith("./") && !findBin(root, program)) throw new Error(`${program} is not installed`);
        const jar = process.env.VERDICT_TLA2TOOLS;
        const r = await execBoxed(argv, { readable: [root, target, ...(jar ? [jar] : [])], writable: [], network: false, env: { VERDICT_TARGET: target } }, root, { timeoutMs: 5 * 60_000 });
        return tail(`exit ${r.code}\n${r.output}`, 200);
      },
    }),
  };
}
